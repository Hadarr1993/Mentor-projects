#!/usr/bin/env node
/**
 * Extracts the inner SVG of the icons the exported documents use, straight
 * from lucide-static, into src/lib/exportIcons.js.
 *
 * The exported HTML has to be self-contained — it is opened offline, in the
 * desert, with no bundler and no network — so it cannot import React
 * components. This keeps those files using the same icon set as the app
 * without hand-copying paths that would drift out of sync.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const iconsDir = join(root, 'node_modules', 'lucide-static', 'icons');

// Semantic name -> lucide file name. Must stay in step with the semantic
// names used by src/components/Icon.jsx for the same concepts.
const WANTED = {
  lunch: 'sun',
  dinner: 'moon',
  users: 'users',
  flame: 'flame',
  water: 'droplets',
  ice: 'snowflake',
  check: 'check',
  clock: 'clock',
  list: 'list-checks',
  chef: 'chef-hat',
  pasta: 'wheat',
  rice: 'cooking-pot',
  soup: 'soup',
  grill: 'beef',
  bread: 'croissant',
  egg: 'egg-fried',
  wrap: 'sandwich',
  noodles: 'utensils-crossed',
  salad: 'salad',
  stew: 'cooking-pot',
  other: 'chef-hat',
  'cat-יבשים': 'wheat',
  'cat-שימורים': 'package',
  'cat-ירקות ופירות': 'carrot',
  'cat-קירור': 'refrigerator',
  'cat-לחם ומאפים': 'croissant',
  'cat-תבלינים ורטבים': 'spray-can',
  'cat-אחר': 'package',
};

const inner = (svg) =>
  svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s+/g, ' ')
    .trim();

const out = {};
const missing = [];
for (const [name, file] of Object.entries(WANTED)) {
  const path = join(iconsDir, `${file}.svg`);
  if (!existsSync(path)) {
    missing.push(`${name} -> ${file}.svg`);
    continue;
  }
  out[name] = inner(readFileSync(path, 'utf8'));
}

if (missing.length) {
  console.error(`gen-export-icons: missing icons:\n  ${missing.join('\n  ')}`);
  process.exit(1);
}

const body = `// GENERATED by scripts/gen-export-icons.mjs — do not edit.
// Inner SVG for the icons used in exported, offline HTML documents.

export const ICON_PATHS = ${JSON.stringify(out, null, 2)};

/** An inline <svg> string for an exported document. */
export function iconSvg(name, size = 16) {
  const body = ICON_PATHS[name] || ICON_PATHS.other;
  return '<svg class="ic" width="' + size + '" height="' + size + '" viewBox="0 0 24 24" ' +
    'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" ' +
    'stroke-linejoin="round" aria-hidden="true">' + body + '</svg>';
}
`;

writeFileSync(join(root, 'src', 'lib', 'exportIcons.js'), body);
console.log(`gen-export-icons: wrote ${Object.keys(out).length} icons`);
